import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { openCompany } from './shortlist';

// Labelled synthetic providers drive the real API, worker and persisted review decisions.
test('partial and completed reviews update the stage and newest checkpoint', async ({ page }, info) => {
  await page.route('**/favicon.ico', route => route.abort());
  await page.route('https://api.brandfetch.io/**', route => route.abort());
  await page.goto('/');
  await page.getByLabel('Company name or website', { exact: true }).fill('https://review-progress.example/');
  const start = page.getByRole('button', { name: 'Start research', exact: true });
  await expect(start).toBeEnabled();
  await page.getByLabel('Company name or website', { exact: true }).press('Tab');
  await expect(start).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('heading', { name: 'Confirm what a good fit means' })).toBeVisible({ timeout: 15000 });
  await page.getByLabel('Companies in this batch').selectOption('3');  // The default is one company; these flows check several.
  await page.getByRole('button', { name: 'Confirm target and discover', exact: true }).press('Enter');
  await expect(page.getByRole('heading', { name: '2 companies researched' })).toBeVisible({ timeout: 15000 });
  const first = await openCompany(page);
  const editor = first.getByRole('region', { name: 'Email draft', exact: true });
  await editor.getByRole('button', { name: 'Create starting draft' }).press('Enter');
  await editor.getByRole('button', { name: 'Save draft', exact: true }).press('Enter');
  await first.getByRole('button', { name: 'Accept company', exact: true }).press('Enter');
  await expect(page.locator('.research-recap > summary')).toContainText('Reviewed 1 of 2 companies');
  await page.locator('.research-recap > summary').press('Enter');
  const stage = page.getByRole('list', { name: 'Research stages' }).getByRole('button', { name: /Review and draft/ });
  await expect(stage).toContainText('Reviewed 1 of 2 companies');
  mkdirSync('.impeccable/review', { recursive: true });
  await stage.focus();
  await expect(stage).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await page.screenshot({ path: `.impeccable/review/${info.project.name}-review-partial.png`, fullPage: true });
  const second = await openCompany(page, 1);
  await second.getByRole('button', { name: 'Reject', exact: true }).press('Enter');
  await expect(stage).toContainText('Reviewed 2 of 2 companies');
  await expect(stage.locator('.status-mark.ok')).toHaveCount(1);
  const latest = page.locator('.checkpoint-list .latest-checkpoint');
  await expect(latest).toContainText('Completed');
  await expect(latest).toContainText('Reviewed 2 of 2 companies');
  await expect(latest).not.toContainText('Waiting');
  await page.reload();
  await expect(page.locator('.research-recap > summary')).toContainText('Reviewed 2 of 2 companies');
  await page.locator('.research-recap > summary').press('Enter');
  await expect(stage).toContainText('Reviewed 2 of 2 companies');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
  await stage.focus();
  await expect(stage).toBeFocused();
  await page.screenshot({ path: `.impeccable/review/${info.project.name}-review-complete.png`, fullPage: true });
});
