import { expect, test } from '@playwright/test';
import { mkdirSync } from 'node:fs';
import { openCompany } from './shortlist';

test('three-company shortlist stays compact and preserves unsaved edits between sheets', async ({ page }, info) => {
  const response = await page.request.post('/__fixture_three_companies');
  const { id } = await response.json();
  await page.goto(`/?run=${id}`);
  await expect(page.getByRole('heading', { name: '3 companies researched' })).toBeVisible({ timeout: 20000 });
  const shortlist = page.getByRole('region', { name: 'Researched companies' });
  const rows = page.locator('.company-item');
  await expect(rows).toHaveCount(3);
  const context = page.getByRole('region', { name: 'Research context' });
  expect(await context.evaluate(element => element.getBoundingClientRect().top)).toBeGreaterThan(
    await shortlist.evaluate(element => element.getBoundingClientRect().bottom));
  await expect(page.locator('.company-item[open]')).toHaveCount(0);
  await expect(rows.first().locator('.company-row')).toContainText('AI software for business operations');
  await expect(rows.first().locator('.company-row')).toContainText('Not reviewed');
  await expect(rows.first().locator('.company-row')).toContainText('No dated company activity established');
  const height = await shortlist.evaluate(element => element.getBoundingClientRect().height);
  expect(height).toBeLessThan(info.project.name === 'phone' ? 1100 : 750);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()?.width ?? 0);
  mkdirSync('.impeccable/review', { recursive: true });
  await page.evaluate(() => document.fonts.ready);
  await page.screenshot({ path: `.impeccable/review/${info.project.name}-shortlist-compact.png`, fullPage: true });
  await shortlist.screenshot({ path: `.impeccable/review/${info.project.name}-shortlist-rows.png` });
  await rows.first().locator('.company-row').press('Enter');
  await expect(rows.first()).toHaveAttribute('open', '');
  const editor = rows.first().getByRole('region', { name: 'Email draft', exact: true });
  await editor.getByRole('button', { name: 'Create starting draft' }).click();
  await editor.getByLabel('Subject', { exact: true }).fill('An unsaved message worth keeping');
  await rows.first().getByLabel('Review note').fill('An unsaved review note');
  await expect(rows.first().locator('.company-row')).toContainText('Unsaved edits');
  await openCompany(page, 1);
  await expect(rows.first()).not.toHaveAttribute('open', '');
  await expect(page.locator('.company-item[open]')).toHaveCount(1);
  await expect(rows.nth(1).getByRole('region', { name: 'People to consider' })).toContainText('No current team roles established');
  await rows.nth(1).getByRole('button', { name: 'Back to shortlist', exact: true }).click();
  await expect(rows.nth(1).locator('.company-row')).toBeFocused();
  await expect(page.locator('.company-item[open]')).toHaveCount(0);
  await rows.first().locator('.company-row').press('Space');
  await expect(editor.getByLabel('Subject', { exact: true })).toHaveValue('An unsaved message worth keeping');
  await expect(rows.first().getByLabel('Review note')).toHaveValue('An unsaved review note');
  await editor.getByRole('button', { name: 'Save draft', exact: true }).click();
  await rows.first().getByRole('button', { name: 'Accept company', exact: true }).click();
  await expect(rows.first().locator('.company-row')).toContainText('Accepted');
  await expect(rows.first().locator('.company-row')).not.toContainText('Unsaved edits');
  await expect(rows.first().locator('.company-panel')).toHaveCSS('opacity', '1');
  await page.screenshot({ path: `.impeccable/review/${info.project.name}-shortlist-open.png`, fullPage: true });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await openCompany(page, 2);
  await expect(rows.nth(2).locator('.company-panel')).toHaveCSS('animation-name', 'none');
  await page.reload();
  await expect(rows.first().locator('.company-row')).toContainText('Accepted');
  await expect(rows.first().locator('.company-row')).toContainText('Draft saved');
  await openCompany(page);
  await expect(editor.getByLabel('Subject', { exact: true })).toHaveValue('An unsaved message worth keeping');
  const saved = await (await page.request.get(`/api/runs/${id}`)).json();
  // Two discovery searches plus the low-yield one: three fixture companies are fewer than one selection pool.
  expect(saved.attempts.filter((attempt: { kind: string }) => attempt.kind === 'search')).toHaveLength(3);
  expect(saved.attempts.filter((attempt: { kind: string }) => attempt.kind === 'model')).toHaveLength(6);
  await page.setViewportSize({ width: 320, height: 844 });
  await page.addStyleTag({ content: 'html { font-size: 200%; }' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(321);
  await openCompany(page, 2);
  await rows.nth(2).getByRole('button', { name: 'Back to shortlist', exact: true }).click();
  await expect(rows.nth(2).locator('.company-row')).toBeFocused();
});


test('linked company activity remains inspectable in the compact shortlist', async ({ page }, info) => {
  const { id } = await (await page.request.post('/__fixture_activity_selection')).json();
  await page.goto(`/?run=${id}`);
  await expect(page.getByRole('heading', { name: '1 company researched' })).toBeVisible({ timeout: 20000 });
  await expect(page.locator('.company-row')).toContainText('Hiring');
  await expect(page.locator('.company-row')).toContainText('Company statement');
  await openCompany(page);
  await page.getByText('Why this company was researched', { exact: true }).click();
  const explanation = page.locator('.selection-reason');
  await expect(explanation).toContainText('we are hiring a sales manager');
  await expect(explanation.locator('a[href="https://activity-fixture.example/news"]')).toBeVisible();
  const saved = await (await page.request.get(`/api/runs/${id}`)).json();
  expect(saved.records[0].research.sources).toHaveLength(4);
  const fetches = saved.attempts.filter((attempt: { kind: string }) => attempt.kind === 'fetch');
  const reused = saved.progress.events.filter((event: { state: string; label: string }) =>
    event.state === 'reused' && event.label.startsWith('Reusing a fresh saved page'));
  expect(fetches.length + reused.length).toBe(4);
  expect(saved.attempts.filter((attempt: { kind: string }) => attempt.kind === 'model')).toHaveLength(2);
  expect(saved.attempts.filter((attempt: { kind: string }) => attempt.kind === 'search')).toHaveLength(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(page.viewportSize()?.width ?? 0);
  mkdirSync('.impeccable/review', { recursive: true });
  await explanation.screenshot({ path: `.impeccable/review/${info.project.name}-linked-activity.png` });
  await page.reload();
  await expect(page.locator('.company-row')).toContainText('Hiring');
});
